"""Impact engine: social, economic and environmental indicators for a land-use state.

Design:
* Calibrated baseline: an unchanged parcel keeps its observed MapPLUTO values.
  Only parcels whose land use changes are modelled, so undoing a change returns
  exactly to the baseline.
* Additive indicators (homes, jobs, value, emissions, runoff, green space) are
  per-parcel sums.
* Access indicators use a 50 m raster convolved with walk-radius disks, so a
  full city recompute takes milliseconds.
* Scores are relative changes within a scope (the affected area, a district or
  the whole city), signed so that a positive score is always a gain.
"""
from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np
import pandas as pd
import yaml
from scipy.signal import fftconvolve

from planarena.config import LAND_USES, PILLARS, PROCESSED, USE_INDEX, USE_KEYS

U = USE_INDEX
N_USES = len(USE_KEYS)
BUILT = np.array([u.built for u in LAND_USES])
COEF_PATH = Path(__file__).with_name("coefficients.yaml")
CALIBRATED_PATH = Path(__file__).with_name("calibrated.yaml")


def load_coefficients(coef_path: Path = COEF_PATH, calibrated_path: Path = CALIBRATED_PATH) -> dict:
    """Provisional defaults, overridden by values generated by ``python -m planarena.calibrate`` (Manhattan) or by
    a city's own calibrated.yaml (other cities)."""
    coef = yaml.safe_load(coef_path.read_text())
    if calibrated_path.exists():
        cal = yaml.safe_load(calibrated_path.read_text())
        for k in ("energy_site_eui_kbtu_per_sqft", "emissions_tco2e_per_kbtu", "emissions_tco2e_per_kbtu_by_use",
                  "jobs_sqft_per_worker"):
            if k in cal:
                coef[k] = cal[k]
        if "persons_per_household" in cal:
            coef["assumptions"]["persons_per_household"] = cal["persons_per_household"]
        coef["calibrated_on"] = cal.get("calibrated_on")
    return coef
SQFT_PER_ACRE = 43560.0


@dataclass(frozen=True)
class Indicator:
    key: str
    label: str
    unit: str
    pillar: str
    direction: int  # +1: more is better, -1: less is better
    kind: str       # "total" or "share"
    provisional: bool
    additive: bool


INDICATORS: tuple[Indicator, ...] = (
    Indicator("homes", "Homes", "units", "economic", 1, "total", False, True),
    Indicator("jobs", "Jobs", "jobs", "economic", 1, "total", True, True),
    Indicator("value", "Tax base (assessed value)", "USD", "economic", 1, "total", False, True),
    Indicator("park_access", "Park within 5-min walk", "% of residents", "social", 1, "share", False, False),
    Indicator("services_access", "Shops & services within 5-min walk", "adequacy 0-1", "social", 1, "share", False, False),
    Indicator("facility_access", "Community facilities within 10-min walk", "adequacy 0-1", "social", 1, "share", False, False),
    Indicator("mix", "Land-use mix around homes", "index 0-1", "social", 1, "share", False, False),
    Indicator("green_space", "Green & open space", "acres", "environmental", 1, "total", False, True),
    Indicator("runoff", "Stormwater runoff", "impervious-equiv. acres", "environmental", -1, "total", True, True),
    Indicator("ghg", "Building emissions", "tCO2e / yr", "environmental", -1, "total", True, True),
    Indicator("green_cover", "Green cover near homes", "% of land within 400 m", "environmental", 1, "share", False, False),
)
# Coefficient groups each indicator depends on; an indicator is flagged provisional while any is.
COEF_DEPENDS = {"jobs": ("jobs_sqft_per_worker",), "runoff": ("runoff_coefficient_c",),
                "ghg": ("energy_site_eui_kbtu_per_sqft", "emissions_tco2e_per_kbtu")}
IND_KEYS = tuple(i.key for i in INDICATORS)
ADDITIVE = tuple(i.key for i in INDICATORS if i.additive)


def _disk(radius_cells: float) -> np.ndarray:
    r = int(np.ceil(radius_cells))
    yy, xx = np.mgrid[-r:r + 1, -r:r + 1]
    return (xx ** 2 + yy ** 2 <= radius_cells ** 2).astype("float64")


class ImpactEngine:
    def __init__(self, parcels: pd.DataFrame, meta: dict, coef_path: Path = COEF_PATH,
                 calibrated_path: Path = CALIBRATED_PATH):
        self.p = parcels.reset_index(drop=True)
        self.meta = meta
        self.coef = load_coefficients(coef_path, calibrated_path)
        self.jobs_cal = 1.0
        self.n = len(self.p)
        self.base_use = self.p["use"].to_numpy().astype("int16")
        self.lot = self.p["lot_area"].to_numpy()
        self.bldg = self.p["bldg_area"].to_numpy()
        self.cd = self.p["cd"].to_numpy()
        self.allowed = self.p["allowed"].to_numpy().astype("int64")
        self.protected = (self.p["landmark"] | self.p["historic"]).to_numpy()
        self.variant = "mid"  # "mid" | "a" | "b": coefficient sensitivity variants
        self._variant_cache: dict = {}
        self._derive()
        self._observed_components()
        self._calibrate_jobs()
        self.provisional = {i.key: any(self.coef.get(g, {}).get("status") == "provisional" for g in COEF_DEPENDS.get(i.key, ()))
                            for i in INDICATORS}
        self._grid()
        self.baseline_state = self.parcel_state(self.base_use)
        raw = self._raw_ratios(self.baseline_state)
        has = self.baseline_state["residents"] > 0
        self.t_serv = float(np.median(raw["serv"][has]))
        self.t_fac = float(np.median(raw["fac"][has]))
        self.value_model = None  # optional ML model: f(use_array, idx) -> values
        # How a changed parcel's quantities are formed (see docs/METHODS.md, "Delta equations"):
        #   "replacement": observed quantities of the old use are removed, modelled ones of the new use added
        #   "difference":  y1 = y_obs + [f(u1, fa1) - f(u0, fa0)], floored at zero
        #   "hybrid":      density-only changes scale the parcel's own observed mix (ratio form);
        #                  use changes remove the observed old use and add the modelled new use
        self.delta_form = "hybrid"
        self.clip_events = 0  # difference form: how often a quantity was floored at zero

    # ------------------------------------------------------------- derived coefficients
    def _derive(self) -> None:
        p = self.p
        res = p[p.use == U["res"]]
        ratio = res.res_area / res.units_res.replace(0, np.nan)
        r_ok = ratio[(ratio > 150) & (ratio < 10000)]
        self.sqft_per_unit = float(r_ok.median())
        # Floor area per home of buildings completed in the ten years up to the twin's latest year of construction: the
        # reference for new construction (recent buildings have larger gross area per home than the stock).
        yb = pd.to_numeric(p.get("year_built", pd.Series(0, index=p.index)), errors="coerce").fillna(0)
        counts = yb[yb > 0].value_counts()
        ref = float(counts[counts >= 20].index.max()) if (counts >= 20).any() else 0.0  # latest real year (typos aside)
        both = p[p.use.isin([U["res"], U["mix"]]) & (p.units_res > 0) & (p.res_area > 0)]
        rb = (both.res_area / both.units_res)[(yb.loc[both.index] > ref - 10) & (yb.loc[both.index] <= ref)]
        rb = rb[(rb > 150) & (rb < 10000)]
        self.sqft_per_unit_new = float(rb.median()) if len(rb) >= 30 else self.sqft_per_unit
        self.unit_rule = "stock"  # "stock": a changed building keeps its own unit size or the stock median;
        # "recent": a new or converted building takes the unit size of recent construction
        # Empirical sensitivity multipliers (Q25/Q50 and Q75/Q50) for modelled quantities.
        self.mult_unit = {"a": float(r_ok.quantile(0.25) / r_ok.median()), "b": float(r_ok.quantile(0.75) / r_ok.median())}
        mix = p[(p.use == U["mix"]) & (p.bldg_area > 0)]
        self.mix_res_share = float((mix.res_area / mix.bldg_area).clip(0, 1).median())
        com = p[p.use == U["com"]]
        tot = max(com.com_area.sum(), 1.0)
        self.com_mix = {
            "office": com.office_area.sum() / tot,
            "retail": com.retail_area.sum() / tot,
        }
        self.com_mix["other"] = max(0.0, 1 - self.com_mix["office"] - self.com_mix["retail"])
        ind = p[p.use == U["ind"]]
        it = max((ind.factory_area + ind.storage_area).sum(), 1.0)
        self.ind_mix = {"factory": ind.factory_area.sum() / it, "storage": ind.storage_area.sum() / it}
        # Value per sq ft, by use and district, from assessed values.
        built = p[p.bldg_area > 0]
        bpsf = ((built.assess_tot - built.assess_land).clip(lower=0) / built.bldg_area)
        self.bldg_psf = bpsf.groupby([built.use, built.cd]).median().to_dict()
        self.bldg_psf_use = bpsf.groupby(built.use).median().to_dict()
        self.bldg_psf_all = float(bpsf.median())
        bp = bpsf[(bpsf > 0) & np.isfinite(bpsf)]
        self.mult_value = {"a": float(bp.quantile(0.75) / bp.median()), "b": float(bp.quantile(0.25) / bp.median())}
        lpsf = (p.assess_land / p.lot_area.replace(0, np.nan))
        self.land_psf_cd = lpsf.groupby(p.cd).median().to_dict()
        self.land_psf_all = float(lpsf.median())
        a = self.coef["assumptions"]
        self.util = float(a["buildout_utilization"]["value"])
        self.pph = float(a["persons_per_household"]["value"])
        far = np.zeros((self.n, N_USES))
        rf, cf, ff = (p[c].to_numpy() for c in ("resid_far", "comm_far", "facil_far"))
        mx = np.maximum.reduce([rf, cf, ff])
        far[:, U["res"]] = np.where(rf > 0, rf, mx)
        far[:, U["mix"]] = np.maximum(rf, cf)
        for k in ("com", "ind", "tra"):
            far[:, U[k]] = np.where(cf > 0, cf, mx)
        far[:, U["pub"]] = np.where(ff > 0, ff, mx)
        self.far = far

    def _calibrate_jobs(self) -> None:
        """Scale floorspace-per-worker so the observed baseline matches a verified employment total."""
        target = self.coef["jobs_sqft_per_worker"].get("calibration_target_jobs")
        if not target:
            return
        jc = self.coef["jobs_sqft_per_worker"]
        o = self.obs
        raw = (o["office"] / jc["office"]["value"] + o["retail"] / jc["retail"]["value"]
               + o["other"] / jc["other_commercial"]["value"] + o["factory"] / jc["factory"]["value"]
               + o["storage"] / jc["storage"]["value"] + o["pubfac"] / jc["public_facility"]["value"]
               + o["trafac"] / jc["transport_utility"]["value"]).sum()
        self.jobs_cal = float(raw / target)

    def derived_summary(self) -> dict:
        return {
            "sqft_per_unit": round(self.sqft_per_unit, 1),
            "mixed_res_share": round(self.mix_res_share, 3),
            "commercial_mix": {k: round(v, 3) for k, v in self.com_mix.items()},
            "industrial_mix": {k: round(v, 3) for k, v in self.ind_mix.items()},
            "median_building_value_psf": round(self.bldg_psf_all, 1),
            "median_land_value_psf": round(self.land_psf_all, 1),
            "services_sqft_per_resident_target": round(self.t_serv, 1),
            "facility_sqft_per_resident_target": round(self.t_fac, 1),
            "jobs_calibration_factor": round(self.jobs_cal, 4),
            "median_roof_share_by_use": {k: round(v, 3) for k, v in self.cov_med.items()},
            "coefficients_calibrated_on": self.coef.get("calibrated_on"),
        }

    # ------------------------------------------------------------- floor-area components
    COMPONENTS = ("res", "office", "retail", "other", "factory", "storage", "pubfac", "trafac")

    def _observed_components(self) -> None:
        p = self.p
        comp = {
            "res": p.res_area.to_numpy(),
            "office": p.office_area.to_numpy(),
            "retail": p.retail_area.to_numpy(),
            "other": p.other_area.to_numpy(),
            "factory": p.factory_area.to_numpy(),
            "storage": p.storage_area.to_numpy(),
        }
        nonres = np.clip(self.bldg - comp["res"], 0, None)
        use = self.base_use
        comp["pubfac"] = np.where(use == U["pub"], nonres, 0.0)
        comp["trafac"] = np.where(use == U["tra"], nonres, 0.0)
        # Commercial area with no recorded breakdown: allocate by the city's commercial mix.
        sub = comp["office"] + comp["retail"] + comp["other"] + comp["factory"] + comp["storage"]
        com_area = p.com_area.to_numpy()
        gap = np.where(np.isin(use, [U["com"], U["mix"]]) & (sub <= 0), com_area, 0.0)
        for k in ("office", "retail", "other"):
            comp[k] = comp[k] + gap * self.com_mix[k]
        # Public and transport lots: all non-residential floor area is counted once, as pubfac/trafac.
        facility_lot = np.isin(use, [U["pub"], U["tra"]])
        for k in ("office", "retail", "other", "factory", "storage"):
            comp[k] = np.where(facility_lot, 0.0, comp[k])
        self.obs = comp
        self.obs_units = p.units_res.to_numpy().astype("float64")
        # A changed building keeps its own observed unit size when it has one (calibration);
        # otherwise the city median applies.
        own = np.divide(p.res_area.to_numpy(), self.obs_units, out=np.zeros(self.n), where=self.obs_units > 0)
        self.unit_size = np.where((own > 250) & (own < 5000), own, self.sqft_per_unit)
        self.obs_value = p.assess_tot.to_numpy().astype("float64")
        # Roof share of each lot: footprint estimated as gross floor area / floors (MapPLUTO).
        fl = p.floors.to_numpy().astype("float64")
        cov = np.divide(self.bldg, fl * self.lot, out=np.full(self.n, np.nan), where=(fl > 0) & (self.lot > 0) & (self.bldg > 0))
        cov = np.clip(cov, 0, 1)
        self.cov_med = {k: float(np.nanmedian(cov[use == U[k]])) if np.isfinite(cov[use == U[k]]).any() else 0.6
                        for k in USE_KEYS}
        fallback = np.array([self.cov_med[k] for k in USE_KEYS])[np.where(use >= 0, use, U["vac"])]
        self.obs_cov = np.where(np.isfinite(cov), cov, np.where(self.bldg > 0, fallback, 0.0))

    def modelled_floor_area(self, use: np.ndarray, idx: np.ndarray, far: np.ndarray | None = None) -> np.ndarray:
        """Total floor area of parcels ``idx`` under their new uses.

        A proposed FAR, if given, sets floor area = lot area x FAR. Otherwise an existing
        building is kept (adaptive reuse), and an unbuilt lot is built to the zoning FAR
        times the build-out utilization.
        """
        u = use[idx]
        keep = (self.bldg[idx] > 0) & BUILT[u]
        build_new = (self.bldg[idx] <= 0) & BUILT[u]
        fa = np.zeros(len(idx))
        fa[keep] = self.bldg[idx][keep]
        fa[build_new] = (self.lot[idx] * self.far[idx, u] * self.util)[build_new]
        if far is not None:
            f = far[idx]
            has = np.isfinite(f) & BUILT[u]
            fa[has] = self.lot[idx][has] * f[has]
        return fa

    def changed_mask(self, use: np.ndarray, far: np.ndarray | None = None) -> np.ndarray:
        ch = np.asarray(use) != self.base_use
        if far is not None:
            built_far = self.p["built_far"].to_numpy()
            ch |= np.isfinite(far) & (np.abs(np.nan_to_num(far) - built_far) > 1e-6)
        return ch

    def _model_components(self, use: np.ndarray, idx: np.ndarray, far: np.ndarray | None = None) -> dict[str, np.ndarray]:
        return self._split(use[idx], self.modelled_floor_area(use, idx, far))

    def _split(self, u: np.ndarray, fa: np.ndarray) -> dict[str, np.ndarray]:
        """Modelled floor-area components of total floor area ``fa`` under uses ``u``."""
        c = {k: np.zeros(len(u)) for k in self.COMPONENTS}
        s = self.mix_res_share
        c["res"] = np.where(u == U["res"], fa, 0) + np.where(u == U["mix"], s * fa, 0)
        c["retail"] = np.where(u == U["mix"], (1 - s) * fa, 0) + np.where(u == U["com"], self.com_mix["retail"] * fa, 0)
        c["office"] = np.where(u == U["com"], self.com_mix["office"] * fa, 0)
        c["other"] = np.where(u == U["com"], self.com_mix["other"] * fa, 0)
        c["factory"] = np.where(u == U["ind"], self.ind_mix["factory"] * fa, 0)
        c["storage"] = np.where(u == U["ind"], self.ind_mix["storage"] * fa, 0)
        c["pubfac"] = np.where(u == U["pub"], fa, 0)
        c["trafac"] = np.where(u == U["tra"], fa, 0)
        c["_fa"] = fa
        return c

    def _model_value(self, use: np.ndarray, idx: np.ndarray, fa: np.ndarray) -> np.ndarray:
        land = np.array([self.land_psf_cd.get(int(d), self.land_psf_all) for d in self.cd[idx]])
        bpsf = np.array([
            self.bldg_psf.get((int(uu), int(d)), self.bldg_psf_use.get(int(uu), self.bldg_psf_all))
            for uu, d in zip(use[idx], self.cd[idx])
        ])
        return self.lot[idx] * np.nan_to_num(land) + fa * np.nan_to_num(bpsf)

    # ------------------------------------------------------------- per-parcel state
    def _cval(self, section: str, key: str | None = None, more_is: str = "a") -> float:
        """Coefficient value for the active sensitivity variant.

        Variant "a" takes the low end of a range when ``more_is == "a"`` and the high end
        otherwise; variant "b" does the opposite.
        """
        c = self.coef[section] if key is None else self.coef[section][key]
        scale = self.jobs_cal if section == "jobs_sqft_per_worker" else 1.0
        if self.variant == "mid":
            return c["value"] * scale
        lo, hi = c.get("low", c["value"]), c.get("high", c["value"])
        return (lo if self.variant == more_is else hi) * scale

    def parcel_state(self, use: np.ndarray, far: np.ndarray | None = None) -> dict[str, np.ndarray]:
        use = np.asarray(use, dtype="int16")
        changed = np.nonzero(self.changed_mask(use, far))[0]
        comp = {k: v.copy() for k, v in self.obs.items()}
        units = self.obs_units.copy()
        value = self.obs_value.copy()
        fa_total = self.bldg.copy()
        mu = 1.0 if self.variant == "mid" else self.mult_unit[self.variant]
        mv = 1.0 if self.variant == "mid" else self.mult_value[self.variant]
        if len(changed):
            m = self._model_components(use, changed, far)
            u0, u1 = self.base_use[changed], use[changed]
            fa0 = self.bldg[changed]
            q = (np.full(len(changed), self.sqft_per_unit_new) if self.unit_rule == "recent"
                 else self.unit_size[changed])
            if self.delta_form == "replacement":
                for k in self.COMPONENTS:
                    comp[k][changed] = m[k]
                units[changed] = m["res"] / (q * mu)
            elif self.delta_form == "difference":
                m0 = self._split(u0, fa0)
                for k in self.COMPONENTS:
                    raw = self.obs[k][changed] + m[k] - m0[k]
                    self.clip_events += int((raw < -1e-6).sum())
                    comp[k][changed] = np.clip(raw, 0, None)
                raw = self.obs_units[changed] + (m["res"] - m0["res"]) / (q * mu)
                self.clip_events += int((raw < -1e-6).sum())
                units[changed] = np.clip(raw, 0, None)
            else:  # hybrid
                # Scale the parcel's own record only when it is internally consistent: at least 1,000 sq ft, and
                # if it has homes, 250-5,000 sq ft per home. Otherwise scaling would amplify a recording error.
                h0 = self.obs_units[changed]
                per = np.divide(fa0, h0, out=np.full(len(changed), 1000.0), where=h0 > 0)
                plausible = (fa0 >= 1000) & ((h0 <= 0) | ((per >= 250) & (per <= 5000)))
                same = (u1 == u0) & plausible
                ratio = np.divide(m["_fa"], fa0, out=np.zeros(len(changed)), where=fa0 > 0)
                for k in self.COMPONENTS:
                    comp[k][changed] = np.where(same, self.obs[k][changed] * ratio, m[k])
                units[changed] = np.where(same, self.obs_units[changed] * ratio, m["res"] / (q * mu))
            fa_total[changed] = m["_fa"]
            old_fa = self.bldg[changed]
            far_set = np.zeros(len(changed), bool) if far is None else np.isfinite(far[changed])
            if self.value_model is not None:
                v_new = self.value_model(use, changed)
                v_old = self.value_model(self.base_use, changed)
                if far_set.any():  # density changes: add floor-area-proportional value from the rate tables
                    fb = self._model_value(use, changed, m["_fa"]) - self._model_value(use, changed, old_fa)
                    v_new = v_new + np.where(far_set, fb, 0.0)
            else:
                v_new = self._model_value(use, changed, m["_fa"])
                v_old = self._model_value(self.base_use, changed, old_fa)
            value[changed] = np.clip(self.obs_value[changed] + mv * (v_new - v_old), 0, None)
        jobs = (comp["office"] / self._cval("jobs_sqft_per_worker", "office")
                + comp["retail"] / self._cval("jobs_sqft_per_worker", "retail")
                + comp["other"] / self._cval("jobs_sqft_per_worker", "other_commercial")
                + comp["factory"] / self._cval("jobs_sqft_per_worker", "factory")
                + comp["storage"] / self._cval("jobs_sqft_per_worker", "storage")
                + comp["pubfac"] / self._cval("jobs_sqft_per_worker", "public_facility")
                + comp["trafac"] / self._cval("jobs_sqft_per_worker", "transport_utility"))
        eui = self.coef["energy_site_eui_kbtu_per_sqft"]
        eui_by_use = np.array([self._cval("energy_site_eui_kbtu_per_sqft", k) if k in eui else 0.0 for k in USE_KEYS])
        efu = self.coef.get("emissions_tco2e_per_kbtu_by_use")
        ef_city = self._cval("emissions_tco2e_per_kbtu")
        ef_by_use = np.array([efu[k]["value"] if efu and k in efu else ef_city for k in USE_KEYS])
        ghg = fa_total * eui_by_use[use] * ef_by_use[use]
        # Rational-method C per parcel: roof share x roof C + open-ground share x ground C of the use.
        ground = np.array([self._cval("runoff_coefficient_c", k) for k in USE_KEYS])
        safe_use = np.where(use >= 0, use, U["vac"])
        cov = self.obs_cov.copy()
        if len(changed):
            new_cov = np.array([self.cov_med[USE_KEYS[u]] for u in safe_use[changed]])
            cov[changed] = np.where(fa_total[changed] <= 0, 0.0, np.where(self.bldg[changed] > 0, self.obs_cov[changed], new_cov))
        c_roof = self.coef["runoff_coefficient_c"].get("roof", {}).get("value", 1.0)
        runoff = self.lot * (cov * c_roof + (1 - cov) * ground[safe_use]) / SQFT_PER_ACRE
        green = np.where(use == U["opn"], self.lot, 0.0) / SQFT_PER_ACRE
        return {
            "use": use, "units": units, "residents": units * self.pph, "value": value,
            "jobs": jobs, "ghg": ghg, "runoff": runoff, "green_space": green,
            "homes": units, "services_fa": comp["retail"] + comp["other"], "pubfac_fa": comp["pubfac"],
            "fa_total": fa_total,
        }

    # ------------------------------------------------------------- access raster
    def _grid(self) -> None:
        g = self.meta["grid"]
        self.nx, self.ny = g["nx"], g["ny"]
        self.cell = (self.p["cy"].to_numpy() * self.nx + self.p["cx"].to_numpy()).astype("int64")
        acc = self.coef["access"]
        cm = g["cell_m"]
        self.k_walk = _disk(acc["walk_radius_m"] / cm)
        self.k_fac = _disk(acc["facility_radius_m"] / cm)
        self.park_min = acc["park_min_sqft"]

    def _raster(self, weights: np.ndarray) -> np.ndarray:
        r = np.bincount(self.cell, weights=weights, minlength=self.nx * self.ny)
        return r.reshape(self.ny, self.nx)

    def _within(self, weights: np.ndarray, kernel: np.ndarray) -> np.ndarray:
        """Value within the kernel around each parcel's cell."""
        conv = fftconvolve(self._raster(weights), kernel, mode="same")
        return np.clip(conv.ravel()[self.cell], 0, None)

    def _raw_ratios(self, st: dict) -> dict[str, np.ndarray]:
        """Floor area within the walk radius per resident within the same radius."""
        res_walk = self._within(st["residents"], self.k_walk)
        res_fac = self._within(st["residents"], self.k_fac)
        serv = np.divide(self._within(st["services_fa"], self.k_walk), res_walk,
                         out=np.zeros(self.n), where=res_walk > 1)
        fac = np.divide(self._within(st["pubfac_fa"], self.k_fac), res_fac,
                        out=np.zeros(self.n), where=res_fac > 1)
        return {"serv": serv, "fac": fac}

    def access(self, st: dict) -> dict[str, np.ndarray]:
        use = st["use"]
        open_area = np.where(use == U["opn"], self.lot, 0.0)
        park = self._within(open_area, self.k_walk) >= self.park_min
        raw = self._raw_ratios(st)
        # Adequacy indices (0-1): per-resident supply against the city's baseline median. Saturating.
        serv = np.clip(raw["serv"] / self.t_serv, 0, 1)
        fac = np.clip(raw["fac"] / self.t_fac, 0, 1)
        groups = [("res",), ("mix", "com"), ("ind", "tra"), ("pub",), ("opn",)]
        land = np.stack([
            self._within(np.where(np.isin(use, [U[k] for k in grp]), self.lot, 0.0), self.k_walk)
            for grp in groups
        ])
        tot = land.sum(axis=0)
        share = np.divide(land, tot, out=np.zeros_like(land), where=tot > 0)
        ent = -(share * np.log(np.where(share > 0, share, 1.0))).sum(axis=0) / np.log(len(groups))
        green_cover = np.divide(land[-1], tot, out=np.zeros_like(tot), where=tot > 0)
        return {"park_access": park, "services_access": serv, "facility_access": fac,
                "mix": ent, "green_cover": green_cover, "serv_raw": raw["serv"], "fac_raw": raw["fac"]}

    # ------------------------------------------------------------- aggregation
    def scope_mask(self, use: np.ndarray, scope: str = "affected", far: np.ndarray | None = None) -> np.ndarray:
        if scope == "city":
            return np.ones(self.n, bool)
        if scope.startswith("cd:"):
            return self.cd == int(scope.split(":")[1])
        changed = self.changed_mask(use, far).astype(float)
        if changed.sum() == 0:
            return np.ones(self.n, bool)
        return self._within(changed, self.k_fac) > 0.5

    def aggregate(self, st: dict, acc: dict, mask: np.ndarray) -> dict[str, float]:
        out = {k: float(st[k][mask].sum()) for k in ADDITIVE}
        w = st["residents"][mask]
        wsum = w.sum()
        for k in ("park_access", "services_access", "facility_access", "mix", "green_cover"):
            v = acc[k][mask].astype(float)
            out[k] = float((v * w).sum() / wsum) if wsum > 0 else float("nan")
        return out

    def _variant_deltas(self, use, far, mask) -> dict[str, list[float]]:
        """Indicator deltas under the low/high coefficient variants (a sensitivity envelope)."""
        out: dict[str, list[float]] = {}
        try:
            for v in ("a", "b"):
                self.variant = v
                if v not in self._variant_cache:
                    bst = self.parcel_state(self.base_use)
                    self._variant_cache[v] = (bst, self.access(bst))
                bst, bacc = self._variant_cache[v]
                st = self.parcel_state(use, far)
                sa, ba = self.aggregate(st, self.access(st), mask), self.aggregate(bst, bacc, mask)
                for k in sa:
                    out.setdefault(k, []).append(sa[k] - ba[k])
        finally:
            self.variant = "mid"
        return out

    def capacity(self, st: dict, mask: np.ndarray, far: np.ndarray | None = None) -> dict:
        """Zoning development capacity: what the rules allow, against what is built."""
        maxfar = self.p["max_far"].to_numpy()
        cap = self.lot * maxfar
        built = st["fa_total"]
        use = st["use"]
        exempt = self.protected | np.isin(use, [U["opn"], U["pub"], U["tra"]])
        built_far = np.divide(built, self.lot, out=np.zeros(self.n), where=self.lot > 0)
        soft = (~exempt) & (maxfar > 0) & (built_far <= 0.5 * maxfar) & (self.lot >= 2500)
        over = np.zeros(self.n, bool) if far is None else (np.isfinite(far) & (np.nan_to_num(far) > maxfar + 1e-6))
        added_capacity = float(((np.nan_to_num(far) - maxfar) * self.lot)[over].sum()) if far is not None else 0.0
        m = mask
        unused = np.clip(cap - built, 0, None) * (~exempt)
        return {
            "zoning_capacity_sqft": float(cap[m].sum()), "built_sqft": float(built[m].sum()),
            "unused_capacity_sqft": float(unused[m].sum()), "soft_sites": int(soft[m].sum()),
            "soft_site_rule": "not protected or civic/park/infrastructure; built FAR <= 50% of max FAR; lot >= 2,500 sq ft",
            "plan_added_capacity_sqft": added_capacity,
            "plan_added_capacity_homes": added_capacity * self.mix_res_share / self.sqft_per_unit if added_capacity else 0.0,
        }

    def soft_site_mask(self) -> np.ndarray:
        cap = self.capacity(self.baseline_state, np.ones(self.n, bool))
        maxfar = self.p["max_far"].to_numpy()
        built_far = np.divide(self.bldg, self.lot, out=np.zeros(self.n), where=self.lot > 0)
        exempt = self.protected | np.isin(self.base_use, [U["opn"], U["pub"], U["tra"]])
        del cap
        return (~exempt) & (maxfar > 0) & (built_far <= 0.5 * maxfar) & (self.lot >= 2500)

    def study_area(self, parcels) -> np.ndarray:
        """Selected parcels plus everything within a 10-minute walk of them."""
        sel = np.zeros(self.n)
        sel[np.asarray(list(parcels), dtype=int)] = 1.0
        return self._within(sel, self.k_fac) > 0.5

    def evaluate(self, use: np.ndarray, scope: str = "affected", pillar_weights: dict | None = None,
                 far: np.ndarray | None = None, ranges: bool = False, mask: np.ndarray | None = None) -> dict:
        use = np.asarray(use, dtype="int16")
        if far is not None:
            far = np.asarray(far, dtype="float64")
        st = self.parcel_state(use, far)
        acc = self.access(st)
        base = self.baseline_state
        bacc = self._base_acc if hasattr(self, "_base_acc") else self._cache_base_acc()
        if mask is None:
            mask = self.scope_mask(use, scope, far)
        else:
            scope = "study area"
        s_agg, b_agg = self.aggregate(st, acc, mask), self.aggregate(base, bacc, mask)
        city_s = self.aggregate(st, acc, np.ones(self.n, bool))
        city_b = self._city_base if hasattr(self, "_city_base") else self._cache_city_base()
        n_changed = int(self.changed_mask(use, far).sum())
        var = self._variant_deltas(use, far, mask) if (ranges and n_changed) else {}
        rows, pillar_scores = [], {p: [] for p in PILLARS}
        for ind in INDICATORS:
            b, s = b_agg[ind.key], s_agg[ind.key]
            d = s - b
            pct = 100 * d / abs(b) if b and np.isfinite(b) and abs(b) > 1e-9 else 0.0
            # Totals score as % change; bounded 0-1 shares score as percentage points.
            raw_score = 100 * d if ind.kind == "share" else pct
            score = float(np.clip(ind.direction * raw_score, -100, 100))
            pillar_scores[ind.pillar].append(score)
            row = asdict(ind) | {
                "baseline": b, "scenario": s, "delta": d, "pct": pct, "score": score,
                "city_baseline": city_b[ind.key], "city_scenario": city_s[ind.key],
                "city_delta": city_s[ind.key] - city_b[ind.key], "provisional": self.provisional[ind.key],
            }
            if ind.key in var:
                vals = var[ind.key] + [d]
                row["range"] = [float(min(vals)), float(max(vals))]
            rows.append(row)
        pillars = {p: float(np.mean(v)) if v else 0.0 for p, v in pillar_scores.items()}
        pw = pillar_weights or {p: 1.0 for p in PILLARS}
        overall = float(sum(pillars[p] * pw.get(p, 0) for p in PILLARS) / max(sum(pw.values()), 1e-9))
        cap_s = self.capacity(st, mask, far)
        cap_b = self.capacity(base, mask)
        return {
            "scope": scope, "scope_parcels": int(mask.sum()), "n_changed": n_changed,
            "indicators": rows, "pillars": pillars, "overall": overall,
            "by_use": self.by_use(st, base),
            "capacity": {"baseline": cap_b, "scenario": cap_s},
            "warnings": self.warnings(use, far),
        }

    def _cache_base_acc(self):
        self._base_acc = self.access(self.baseline_state)
        return self._base_acc

    def _cache_city_base(self):
        self._city_base = self.aggregate(self.baseline_state, self._base_acc if hasattr(self, "_base_acc") else self._cache_base_acc(), np.ones(self.n, bool))
        return self._city_base

    def by_use(self, st: dict, base: dict) -> list[dict]:
        out = []
        for u in LAND_USES:
            i = U[u.key]
            ms, mb = st["use"] == i, base["use"] == i
            row = {"use": u.key, "label": u.label, "color": u.color,
                   "parcels": int(ms.sum() - mb.sum()),
                   "acres": float((self.lot[ms].sum() - self.lot[mb].sum()) / SQFT_PER_ACRE),
                   "floor_area": float(st["fa_total"][ms].sum() - base["fa_total"][mb].sum())}
            for k in ("homes", "jobs", "value", "ghg", "runoff", "green_space"):
                row[k] = float(st[k][ms].sum() - base[k][mb].sum())
            out.append(row)
        return out

    # ------------------------------------------------------------- conversion precedent (realism)
    precedent = None

    def set_precedent(self, table: dict) -> None:
        """Observed conversions by (from use, to use, building size class); see planarena.models.transition."""
        c = np.array(table["counts"])
        # A conversion seen in a larger building class is also plausible in smaller ones.
        self.precedent = np.flip(np.cumsum(np.flip(c[:, :, 1:], axis=2), axis=2), axis=2)
        self.precedent_edges = np.array(table["size_bins_sqft"][1:])

    def has_precedent(self, idx: np.ndarray, new_use: np.ndarray) -> np.ndarray:
        """True when converting the existing building on each parcel to ``new_use`` was observed at least once
        in Manhattan 2015-2025 at that building size or larger. Unbuilt lots always pass (new construction)."""
        idx = np.asarray(idx)
        if self.precedent is None or not len(idx):
            return np.ones(len(idx), bool)
        b = self.bldg[idx]
        cls = np.searchsorted(self.precedent_edges, b, side="right")
        cur = self.base_use[idx]
        ok = (b <= 0) | (cur < 0) | (new_use == cur)
        valid = (cur >= 0) & (new_use >= 0)
        hits = np.zeros(len(idx), bool)
        hits[valid] = self.precedent[cur[valid], new_use[valid], cls[valid]] > 0
        return ok | hits

    def warnings(self, use: np.ndarray, far: np.ndarray | None = None) -> list[dict]:
        changed = np.nonzero(self.changed_mask(use, far))[0]
        if not len(changed):
            return []
        use_changed = changed[use[changed] != self.base_use[changed]]
        bit = (self.allowed[use_changed] >> np.clip(use[use_changed], 0, None)) & 1
        zoning = use_changed[(bit == 0) & (use[use_changed] >= 0)]
        prot = changed[self.protected[changed]]
        lost_homes = use_changed[(self.obs_units[use_changed] > 0) & ~np.isin(use[use_changed], [U["res"], U["mix"]])]
        w = []
        if len(zoning):
            w.append({"type": "zoning", "count": int(len(zoning)), "parcels": zoning[:200].tolist(),
                      "message": f"{len(zoning)} parcel(s) changed to a use their zoning district does not normally allow (rezoning needed)."})
        if far is not None:
            maxfar = self.p["max_far"].to_numpy()
            up = changed[np.isfinite(far[changed]) & (np.nan_to_num(far[changed]) > maxfar[changed] + 1e-6)]
            if len(up):
                w.append({"type": "density", "count": int(len(up)), "parcels": up[:200].tolist(),
                          "message": f"{len(up)} parcel(s) exceed the maximum FAR their zoning allows (an upzoning would be needed)."})
        if len(prot):
            w.append({"type": "protected", "count": int(len(prot)), "parcels": prot[:200].tolist(),
                      "message": f"{len(prot)} parcel(s) are landmarks or in historic districts."})
        if self.precedent is not None and len(use_changed):
            nop = use_changed[~self.has_precedent(use_changed, use[use_changed])]
            if len(nop):
                w.append({"type": "precedent", "count": int(len(nop)), "parcels": nop[:200].tolist(),
                          "message": f"{len(nop)} conversion(s) of existing buildings have no precedent in Manhattan "
                                     "2015-2025 at that building size (e.g. a large office tower to a public facility)."})
        if len(lost_homes):
            n_units = int(self.obs_units[lost_homes].sum())
            w.append({"type": "displacement", "count": int(len(lost_homes)), "parcels": lost_homes[:200].tolist(),
                      "message": f"{n_units} existing homes on {len(lost_homes)} parcel(s) would be removed or converted."})
        return w


def load_engine(processed: Path = PROCESSED) -> ImpactEngine:
    parcels = pd.read_parquet(processed / "parcels.parquet")
    meta = json.loads((processed / "twin_meta.json").read_text())
    own = processed / "calibrated.yaml"
    e = ImpactEngine(parcels, meta, calibrated_path=own if own.exists() else CALIBRATED_PATH)
    f = processed / "conversion_precedent.json"
    if f.exists():
        e.set_precedent(json.loads(f.read_text()))
    return e
